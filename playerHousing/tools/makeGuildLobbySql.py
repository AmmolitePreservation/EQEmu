"""Writes sql/guildLobby.sql: the Guild Lobby's version 1, Live's lobby from House of Thule on, routed by expansion (DOR-17).

Version 0 stays the lobby RoF2's 2005 art knows (AFRAME_, GUILD_DOOR_, TRANS_ENTRY, no gate) through Underfoot (16). Version 1 is
Live's: PEQ already carries its doors (Live's 36 at Live's ids plus 39, the gate OBJ_IRONGATESWITCH at 77, type 159, at Live's exact
position), its spawn points and objects, but no zone row, no zone point and no instance. This content gives version 0 its last
expansion, copies version 0's zone row as version 1 from House of Thule (17) on, renumbers the doors to Live's ids (the gate becomes
38), copies the zone point to the Plane of Knowledge, and adds the global never-expiring instance EQEmu's zone routing needs
(common/content/world_content_service.cpp FindZone, as PEQ routes lavastorm): players zone into the version their server's expansion
passes, with no routing code. housingDoors.sql then sets the gate's RealEstateDoorID at version 1 (DOR-19). The SQL refuses a
second run and a version 1 whose doors are not PEQ's 36, and loads in one transaction.

Usage: python makeGuildLobbySql.py --live <livedumps clone>
"""
import argparse, os, sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from eqemuColumns import columnsOf  # noqa: E402
from makeGuildServicesSql import quote  # noqa: E402
from makeHousingDoorsSql import readLiveDoors, guildLobbyZoneID, gateDoorID, gateModel, typeNeighborhoodList  # noqa: E402

sqlPath = os.path.join(here, '..', 'sql', 'guildLobby.sql')
lobby, liveVersion = 'guildlobby', 1
underfoot, houseOfThule = 16, 17
peqIdOffset = 39
positionUnits = 1.0
versionNote = "Live's lobby from House of Thule on, the way into the neighborhoods (player housing, DOR-17)"
# instance_list.notes holds 50 characters.
instanceNote = 'Guild Lobby V1 - House of Thule (player housing)'


def liveLobbyDoors(liveDoors):
  """Live's lobby doors by id, checked: the gate is the neighborhood list door 38, every door fits a PEQ id under 256 after the offset."""
  doors = {door['id']: door for (zone, _), door in liveDoors.items() if zone == lobby}
  if not doors:
    raise ValueError("Live's doors hold no guildlobby door")
  gate = doors.get(gateDoorID)
  if gate is None or gate['name'] != gateModel or gate['type'] != typeNeighborhoodList:
    raise ValueError(f"Live's guildlobby door {gateDoorID} is not a type-{typeNeighborhoodList} {gateModel}")
  if max(doors) + peqIdOffset > 255 or min(doors) < 1:
    raise ValueError(f"Live's lobby door ids {min(doors)}-{max(doors)} do not fit PEQ's offset of {peqIdOffset}")
  return doors


def doorCondition(doorId, door):
  return (f"(doorid = {doorId + peqIdOffset} AND name = '{door['name']}' AND opentype = {door['type']}"
          + ''.join(f' AND ABS(pos_{axis} - ({door[axis]!r})) <= {positionUnits!r}' for axis in 'xyz') + ')')


def renderSql(doors, zoneColumns, zonePointColumns):
  zoneId = guildLobbyZoneID()
  substitutes = {'version': str(liveVersion), 'min_expansion': str(houseOfThule), 'max_expansion': '-1', 'note': quote(versionNote)}
  zoneSelect = ', '.join(substitutes.get(column, f'`{column}`') for column in zoneColumns)
  pointSelect = ', '.join(str(liveVersion) if column == 'version' else f'`{column}`' for column in zonePointColumns)
  matches = '\n      OR '.join(doorCondition(doorId, door) for doorId, door in sorted(doors.items()))
  return f"""-- Generated by playerHousing/tools/makeGuildLobbySql.py from Live's doors: the Guild Lobby's version 1 from House of Thule on (DOR-17); loads before housingDoors.sql.
DELIMITER //
BEGIN NOT ATOMIC
  DECLARE templateId INT DEFAULT NULL;
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  IF EXISTS (SELECT 1 FROM zone WHERE short_name = '{lobby}' AND version = {liveVersion}) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'the Guild Lobby already has a version {liveVersion} zone row';
  END IF;
  IF EXISTS (SELECT 1 FROM instance_list WHERE zone = {zoneId} AND version = {liveVersion} AND is_global = 1 AND never_expires = 1) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'the Guild Lobby version {liveVersion} already has its global instance';
  END IF;
  IF (SELECT COUNT(*) FROM doors WHERE zone = '{lobby}' AND version = {liveVersion}) <> {len(doors)}
      OR (SELECT COUNT(*) FROM doors WHERE zone = '{lobby}' AND version = {liveVersion} AND ({matches})) <> {len(doors)} THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'the Guild Lobby version {liveVersion} doors are not PEQ''s {len(doors)} rows at Live''s ids plus {peqIdOffset}, Live''s names, types and positions';
  END IF;
  IF (SELECT COUNT(*) FROM zone_points WHERE zone = '{lobby}' AND version = 0) <> 1 THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'the Guild Lobby version 0 does not have exactly one zone point to copy';
  END IF;
  SELECT id INTO templateId FROM zone WHERE short_name = '{lobby}' AND version = 0 ORDER BY id LIMIT 1;
  IF templateId IS NULL THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'no version 0 Guild Lobby zone row to copy';
  END IF;
  START TRANSACTION;
  UPDATE zone SET max_expansion = {underfoot} WHERE id = templateId;
  INSERT INTO zone ({', '.join(f'`{column}`' for column in zoneColumns)})
    SELECT {zoneSelect} FROM zone WHERE id = templateId;
  UPDATE doors SET doorid = doorid - {peqIdOffset} WHERE zone = '{lobby}' AND version = {liveVersion} AND doorid BETWEEN {min(doors) + peqIdOffset} AND {max(doors) + peqIdOffset};
  INSERT INTO zone_points ({', '.join(f'`{column}`' for column in zonePointColumns)})
    SELECT {pointSelect} FROM zone_points WHERE zone = '{lobby}' AND version = 0;
  INSERT INTO instance_list (zone, version, is_global, start_time, duration, never_expires, notes) VALUES ({zoneId}, {liveVersion}, 1, 0, 0, 1, {quote(instanceNote)});
  COMMIT;
END //
DELIMITER ;
SELECT zoneidnumber, version, min_expansion, max_expansion, note FROM zone WHERE short_name = '{lobby}' ORDER BY version;
SELECT version, COUNT(*), MIN(doorid), MAX(doorid), SUM(opentype = {typeNeighborhoodList}) FROM doors WHERE zone = '{lobby}' GROUP BY version;
"""


def main():
  parser = argparse.ArgumentParser(description='Write sql/guildLobby.sql.')
  parser.add_argument('--live', required=True, help='a livedumps clone')
  live = parser.parse_args().live
  doors = liveLobbyDoors(readLiveDoors(live))
  with open(sqlPath, 'w', newline='\n', encoding='utf-8') as file:
    file.write(renderSql(doors, columnsOf('zone'), columnsOf('zone_points')))
  print(f'wrote {sqlPath}: version {liveVersion} from expansion {houseOfThule}, {len(doors)} doors renumbered, the gate {gateDoorID}')


if __name__ == '__main__':
  main()
