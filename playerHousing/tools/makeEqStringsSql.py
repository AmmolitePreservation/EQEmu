"""Writes sql/eqStrings.sql: the eqstr_us.txt strings Peridot changes (content/eqStringChanges.tsv) as updates of eq_str (PAT-8).

eq_str holds RoF2's eqstr_us.txt once import_client_files has read it from import/; the SQL refuses an empty table and an id the
table lacks, so a change never lands on a string that is not there, and export_client_files writes the whole file afterwards.

Usage: python makeEqStringsSql.py
"""
import csv, os

here = os.path.dirname(os.path.abspath(__file__))
changesPath = os.path.join(here, '..', 'content', 'eqStringChanges.tsv')
sqlPath = os.path.join(here, '..', 'sql', 'eqStrings.sql')


def quote(text):
  return "'" + text.replace('\\', '\\\\').replace("'", "''") + "'"


def readChanges(path=changesPath):
  with open(path, newline='', encoding='utf-8') as file:
    rows = list(csv.DictReader(file, delimiter='\t', quoting=csv.QUOTE_NONE))
  changes = {}
  for row in rows:
    if not row['id'].isdigit():
      raise ValueError(f'eqstr id {row["id"]!r} is not a number')
    if not row['text'] or '\r' in row['text'] or '\n' in row['text']:
      raise ValueError(f'eqstr {row["id"]} has no text or a line break in it')
    if int(row['id']) in changes:
      raise ValueError(f'eqstr {row["id"]} is listed twice')
    changes[int(row['id'])] = row['text']
  if not changes:
    raise ValueError('content/eqStringChanges.tsv lists no change')
  return changes


def renderSql(changes):
  ids = ', '.join(str(stringId) for stringId in sorted(changes))
  updates = '\n'.join(f'  UPDATE eq_str SET value = {quote(text)} WHERE id = {stringId};' for stringId, text in sorted(changes.items()))
  return f"""-- Generated by playerHousing/tools/makeEqStringsSql.py from content/eqStringChanges.tsv: the eqstr_us.txt strings Peridot changes (PAT-8).
DELIMITER //
BEGIN NOT ATOMIC
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  IF NOT EXISTS (SELECT 1 FROM eq_str) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'eq_str is empty: import the client''s eqstr_us.txt with import_client_files first';
  END IF;
  IF (SELECT COUNT(*) FROM eq_str WHERE id IN ({ids})) <> {len(changes)} THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'eq_str lacks a string the content changes';
  END IF;
  START TRANSACTION;
{updates}
  COMMIT;
END //
DELIMITER ;
"""


def main():
  changes = readChanges()
  with open(sqlPath, 'w', newline='\n', encoding='utf-8') as file:
    file.write(renderSql(changes))
  print(f'wrote {sqlPath}: {len(changes)} strings ({", ".join(str(stringId) for stringId in sorted(changes))})')


if __name__ == '__main__':
  main()
