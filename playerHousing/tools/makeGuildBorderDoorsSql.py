"""Writes sql/guildBorderDoors.sql: the neighborhood's four guild plot borders (OBP_GUILDSQUARE) become Live's doors 226-229.

PEQ ships the four guild borders as OBP_GUILDSQUARE doors (199-202 on Peridot), each within a unit of Live's. The SQL matches
every one to its Live door by position and sets Live's id, position, heading and size; every other column stays PEQ's, so
nothing about door behavior is chosen here. Each Live door is matched to its guild plot in content/sunriseHillsPlots.json.
The door rules hold (DOR-10): ids below 256, the client keeps door ids in a byte; a model name longer than 3 characters and
upper case, as the client's lookup needs; and each door closed with its state not inverted, or the click is stopped. The
neighborhood loads the model through its own asset list (stonesquare.eqg).

Usage: python makeGuildBorderDoorsSql.py --live <livedumps clone>
"""
import argparse, csv, json, math, os, re

here = os.path.dirname(os.path.abspath(__file__))
doorIds = [226, 227, 228, 229]
modelName = 'OBP_GUILDSQUARE'
plotMatchUnits = 1.0
idList = ', '.join(map(str, doorIds))
maxDoorId = 255


def liveDoors(live):
  rows = [row for row in csv.DictReader(open(os.path.join(live, 'master', 'doors.tsv'), encoding='latin-1'), delimiter='\t')
          if row['zone'] == 'neighborhood' and int(row['id']) in doorIds]
  if sorted(int(row['id']) for row in rows) != doorIds or any(row['name'] != modelName or row['type'] != '160' for row in rows):
    raise ValueError(f"Live's doors {doorIds} are not the neighborhood's four {modelName} doors of type 160")
  return sorted(rows, key=lambda row: int(row['id']))


def guildPlot(door, plots):
  x, y = float(door['x']), float(door['y'])
  distance, plot = min((math.hypot(plot['doorPosition'][0] - x, plot['doorPosition'][1] - y), plot['address']) for plot in plots)
  if distance > plotMatchUnits:
    raise ValueError(f"Live door {door['id']}: no guild plot within {plotMatchUnits} units ({distance:.2f})")
  return plot


def updateStatement(door, address):
  if not 0 <= float(door['heading']) < 512:
    raise ValueError(f"Live door {door['id']}: heading {door['heading']} is outside [0, 512)")
  x, y = float(door['x']), float(door['y'])
  match = (f"zone = 'neighborhood' AND name = '{modelName}' AND doorid NOT IN ({idList}) "
           f"AND ABS(pos_x - {x!r}) < {plotMatchUnits} AND ABS(pos_y - {y!r}) < {plotMatchUnits}")
  return (f"  -- {address}\n"
          f"  IF (SELECT COUNT(*) FROM doors WHERE {match}) <> 1 THEN\n"
          f"    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'not exactly one PEQ {modelName} door within {plotMatchUnits} unit of Live door {door['id']}';\n"
          f"  END IF;\n"
          f"  UPDATE doors SET doorid = {door['id']}, pos_x = {x!r}, pos_y = {y!r}, pos_z = {float(door['z'])!r}, "
          f"heading = {float(door['heading'])!r}, size = {int(door['scaleFactor'])} WHERE {match};\n")


def main():
  parser = argparse.ArgumentParser(description='Write sql/guildBorderDoors.sql.')
  parser.add_argument('--live', required=True, help='a livedumps clone')
  live = parser.parse_args().live
  if not re.fullmatch(r'[A-Z0-9_]{4,}', modelName) or max(doorIds) > maxDoorId:
    raise ValueError('the guild border doors break the door rules')
  if 'stonesquare.eqg' not in open(os.path.join(here, '..', 'content', 'neighborhoodAssets.txt')).read().split():
    raise ValueError(f'the neighborhood does not load {modelName} (stonesquare.eqg)')
  plots = [row for row in json.load(open(os.path.join(here, '..', 'content', 'sunriseHillsPlots.json'))) if row['kind'] == 'guild plot']
  doors = liveDoors(live)
  addresses = [guildPlot(door, plots) for door in doors]
  if sorted(addresses) != sorted(plot['address'] for plot in plots):
    raise ValueError("Live's guild border doors and the template's guild plots do not match one to one")
  updates = ''.join(updateStatement(door, address) for door, address in zip(doors, addresses))
  sql = f"""-- Generated by playerHousing/tools/makeGuildBorderDoorsSql.py from Live's doors and content/sunriseHillsPlots.json.
DELIMITER //
BEGIN NOT ATOMIC
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  START TRANSACTION;
  IF EXISTS (SELECT 1 FROM doors WHERE zone = 'neighborhood' AND doorid IN ({idList})) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'the neighborhood already has doors {idList}';
  END IF;
  IF (SELECT COUNT(*) FROM doors WHERE zone = 'neighborhood' AND name = '{modelName}' AND opentype = 160 AND doorisopen = 0 AND invert_state = 0) <> {len(doorIds)}
     OR (SELECT COUNT(*) FROM doors WHERE zone = 'neighborhood' AND name = '{modelName}') <> {len(doorIds)} THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'the neighborhood does not have exactly {len(doorIds)} closed, uninverted type-160 {modelName} doors';
  END IF;
{updates}  COMMIT;
END //
DELIMITER ;
SELECT doorid, name, pos_x, pos_y, pos_z, heading, opentype, size FROM doors WHERE zone = 'neighborhood' AND name = '{modelName}' ORDER BY doorid;
"""
  path = os.path.join(here, '..', 'sql', 'guildBorderDoors.sql')
  open(path, 'w', encoding='ascii').write(sql)
  print(f'wrote {os.path.relpath(path)}: {len(doors)} guild borders')


if __name__ == '__main__':
  main()
