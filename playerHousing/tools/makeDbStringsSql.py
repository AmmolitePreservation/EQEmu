"""Writes sql/dbStrings.sql: the dbstr_us.txt category-28 rows the training dummies' menus label with (PAT-1), as db_str rows.

RoF2's dbstr_us.txt has none of them; Live's client resolves each entry's label from them, and MQ2PeridotLive captured the text
beside its id in every dummy menu (livedumps master/menus.tsv: a type-9 action's third number and a type-10 submenu's name the
category-28 string). export_client_files then writes them into dbstr_us.txt with the rest of db_str. The SQL refuses existing rows.

Usage: python makeDbStringsSql.py --live <livedumps clone>
"""
import argparse, csv, os, re

here = os.path.dirname(os.path.abspath(__file__))
sqlPath = os.path.join(here, '..', 'sql', 'dbStrings.sql')
trainingDummies = range(66700, 66717)
menuLabelCategory = 28
labeledEntryTypes = ('9', '10')


def quote(text):
  return "'" + text.replace('\\', '\\\\').replace("'", "''") + "'"


def dummyLabels(live):
  """Label id -> text, from every captured training dummy menu; a label with two texts fails."""
  labels = {}
  with open(os.path.join(live, 'master', 'menus.tsv'), newline='', encoding='latin-1') as file:
    for row in csv.DictReader(file, delimiter='\t', quoting=csv.QUOTE_NONE):
      if not row['itemId'].isdigit() or int(row['itemId']) not in trainingDummies:
        continue
      for entry in row['entries'].split(' | '):
        found = re.match(r'(\d+):(-?\d+):(-?\d+):(-?\d+) (.+)$', entry)
        if not found or found.group(1) not in labeledEntryTypes:
          continue
        labelId, text = int(found.group(3)), found.group(5)
        if labels.setdefault(labelId, text) != text:
          raise ValueError(f'label {labelId} reads {labels[labelId]!r} and {text!r}')
  if not labels:
    raise ValueError('no training dummy menu in the captures')
  return dict(sorted(labels.items()))


def renderSql(labels):
  ids = ', '.join(str(labelId) for labelId in labels)
  rows = ',\n'.join(f'    ({labelId}, {menuLabelCategory}, {quote(text)})' for labelId, text in labels.items())
  return f"""-- Generated by playerHousing/tools/makeDbStringsSql.py: the training dummies' menu labels, dbstr category 28 (PAT-1).
DELIMITER //
BEGIN NOT ATOMIC
  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
  IF EXISTS (SELECT 1 FROM db_str WHERE type = {menuLabelCategory} AND id IN ({ids})) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'db_str already holds a training dummy label';
  END IF;
  START TRANSACTION;
  INSERT INTO db_str (id, type, value) VALUES
{rows};
  COMMIT;
END //
DELIMITER ;
"""


def main():
  parser = argparse.ArgumentParser(description='Write sql/dbStrings.sql.')
  parser.add_argument('--live', required=True, help='a livedumps clone')
  live = parser.parse_args().live
  labels = dummyLabels(live)
  with open(sqlPath, 'w', newline='\n', encoding='utf-8') as file:
    file.write(renderSql(labels))
  print(f'wrote {sqlPath}: {len(labels)} labels, {min(labels)} to {max(labels)}')


if __name__ == '__main__':
  main()
