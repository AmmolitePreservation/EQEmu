"""Map every use of every client-bound control in one window's code.

For each control the window binds (window member offset, from guiControlInventory.md), list
every instruction in the window's code range that loads that member, and classify what the
code does with it next. This is a checklist for reading, not a conclusion: every site still
has to be read to know the condition behind it.

Classification (first match within the next few instructions after the load):
  enable      call 0x866610 (CXWnd enable, sets control +0x1a)
  show        call through vtable +0xd8
  text        call through vtable +0x124
  check       call through vtable +0x170 (set checked state)
  click       the load is a compare in the notification handler (cmp reg, [this+off])
  list:<fn>   a known listbox/combobox helper
  read:<off>  a field read from the control (for example +0x1a enabled, +0x196 visible, +0x1e4 checked)
  call:<fn>   any other direct call with the control in ecx
  other       none of the above

Usage:
  python controlUsageMap.py <eqgame.exe> <guiControlInventory.md> <prefix> <codeStart hex> <codeEnd hex> <output .md>
"""
import collections
import re
import sys

from realEstateOpcodeScan import ClientImage

knownHelpers = {
  0x866610: "enable", 0x857630: "list:setCellWindow", 0x8575b0: "list:setCellText",
  0x853430: "list:currentRow", 0x853680: "list:rowData", 0x853910: "list:clickedCell",
  0x86a780: "combo:currentIndex", 0x86a7f0: "combo:itemData", 0x86a960: "combo:clear",
  0x86ae50: "combo:addItem", 0x86a740: "combo:select", 0x86a770: "combo:count",
}


def boundControls(inventoryPath, prefix):
  controls = {}
  for line in open(inventoryPath, encoding="utf-8"):
    match = re.match(r"\| ([^|]+) \| `(%s_\w+)` \|[^|]*\|[^|]*\| `\+(0x[0-9a-f]+)`" % prefix, line)
    if match:
      controls[int(match.group(3), 16)] = (match.group(2), match.group(1).strip())
  return controls


def classify(instructions, index, register):
  start = instructions[index]
  if start.mnemonic == "cmp":
    return "click"
  holders = {register}
  for following in instructions[index + 1:index + 10]:
    operands = following.op_str
    copy = re.match(r"(e\w\w), (e\w\w)$", operands)
    if following.mnemonic == "mov" and copy and copy.group(2) in holders:
      holders.add(copy.group(1))
    fieldRead = re.search(r"\[(e\w\w) \+ (0x[0-9a-f]+)\]", operands)
    if fieldRead and fieldRead.group(1) in holders and following.mnemonic in ("cmp", "mov", "movzx", "test"):
      vtableLoad = following.mnemonic == "mov" and re.match(r"e\w\w, dword ptr \[e\w\w\]$", operands)
      if not vtableLoad:
        return "read:+" + fieldRead.group(2)
    if following.mnemonic == "call":
      target = operands
      if target.startswith("0x"):
        address = int(target, 16)
        return knownHelpers.get(address, f"call:{target}")
      slot = re.search(r"\+ (0x[0-9a-f]+)\]$", target)
      registerCall = re.match(r"e\w\w$", target)
      window = instructions[max(0, index):instructions.index(following)]
      slots = [re.search(r"\+ (0x[0-9a-f]+)\]$", w.op_str) for w in window if w.mnemonic == "mov" and re.search(r"\[e\w\w \+ 0x[0-9a-f]+\]$", w.op_str)]
      slotValue = slot.group(1) if slot else (slots[-1].group(1) if registerCall and slots and slots[-1] else None)
      return {"0xd8": "show", "0x124": "text", "0x170": "check"}.get(slotValue, f"vcall:+{slotValue}")
  return "other"


def main():
  if len(sys.argv) != 7:
    print(__doc__)
    return 2
  exePath, inventoryPath, prefix, startText, endText, outputPath = sys.argv[1:]
  client = ClientImage(exePath)
  controls = boundControls(inventoryPath, prefix)
  if not controls:
    raise RuntimeError(f"No bound {prefix}_ controls found in {inventoryPath}")
  start, end = int(startText, 16), int(endText, 16)
  instructions = client.linearDisassembly(start, end)
  uses = collections.defaultdict(list)
  for index, instruction in enumerate(instructions):
    for match in re.finditer(r"\[(e\w\w) \+ (0x[0-9a-f]+)\]", instruction.op_str):
      offset = int(match.group(2), 16)
      if offset not in controls or match.group(1) == "esp":
        continue
      target = instruction.op_str.split(",")[0].strip()
      register = target if re.match(r"e\w\w$", target) else None
      if instruction.mnemonic == "mov" and not register:
        uses[offset].append((instruction.address, "store"))
        continue
      uses[offset].append((instruction.address, classify(instructions, index, register)))
  lines = [f"# {prefix} control usage map (generated)", "",
           f"Generated by `controlUsageMap.py` over `{start:#x}`-`{end:#x}`. One row per bound control; every site must be read before the control's analysis row can be marked done.", "",
           "| Control | Type | Offset | Sites (address: kind) |", "|---|---|---|---|"]
  for offset in sorted(controls, key=lambda o: controls[o][0]):
    name, kind = controls[offset]
    sites = ", ".join(f"`{a:#x}`: {k}" for a, k in uses.get(offset, [])) or "**none found**"
    lines.append(f"| `{name}` | {kind} | `+{offset:#x}` | {sites} |")
  with open(outputPath, "w", encoding="utf-8") as outFile:
    outFile.write("\n".join(lines) + "\n")
  total = sum(len(v) for v in uses.values())
  print(f"{len(controls)} controls, {total} sites, {sum(1 for o in controls if o not in uses)} controls with no sites")
  return 0


if __name__ == "__main__":
  sys.exit(main())
